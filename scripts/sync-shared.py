#!/usr/bin/env python3
"""Renders the memory protocol in shared/ into each client's instruction files.

    python3 scripts/sync-shared.py          # write
    python3 scripts/sync-shared.py --check  # exit 1 if a generated file is out of date

One source (shared/protocol.md, shared/tools.md), one line of per-client facts below. The endpoint
and bank label are the same everywhere, so they live here once.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROTOCOL = (ROOT / "shared/protocol.md").read_text()
TOOLS = (ROOT / "shared/tools.md").read_text()
REACTOR = (ROOT / "shared/reactor.md").read_text()
NOTE = "<!-- Generated by scripts/sync-shared.py from shared/. Edit shared/, not this file. -->\n"

CLIENTS = {
    "cursor": "cursor",
    "codex": "codex",
}


def protocol(agent: str) -> str:
    return PROTOCOL.replace("{{AGENT}}", agent)


def rule(agent):
    return (
        "---\ndescription: Use Hippocampus long-term memory (recall at the start, retain what should outlive the session)\n"
        "alwaysApply: true\n---\n" + NOTE + "\nYou have long-term memory through the `hippocampus` MCP server.\n\n" + protocol(agent)
    )


def skill(agent):
    return (
        "---\nname: hippocampus\ndescription: Use the Hippocampus MCP as the user's long-term memory. Use when the task depends on "
        "what the user decided, prefers, or did in earlier sessions, or when the user says remember, recall, or forget.\n---\n"
        + NOTE + "\n# Hippocampus memory\n\nOne bank per agent: your bank is named by the `X-Agent-ID` header (`{agent}`); no tool takes a bank. "
        f"Your calls are recorded as the agent `{agent}` (the `X-Agent-ID` header), so what you did and what the user said stay distinguishable.\n\n"
        + TOOLS + "\n" + protocol(agent)
    )


def reactor_skill():
    return (
        "---\nname: reactor\ndescription: Use the Reactor hub to reach the user's connected services (maps, finance, trips, tasks, FPL, Notion and "
        "more). Use when a task needs a capability you have no direct tool for, or before concluding you lack one.\n---\n"
        + NOTE + "\n# Reactor hub\n\nThe `reactor` MCP server is the user's tool belt: four entry tools with the whole connected ecosystem behind them.\n\n" + REACTOR
    )


def reactor_rule():
    return (
        "---\ndescription: Use the Reactor hub to find tools before concluding a capability is missing\nalwaysApply: true\n---\n"
        + NOTE + "\nYou have the user's connected services through the `reactor` MCP server.\n\n" + REACTOR
    )


def agents_md(agent):
    return (
        NOTE + "## Long-term memory (Hippocampus)\n\nYou have long-term memory through the `hippocampus` MCP server. "
        f"One bank per agent: yours is '{agent}', named by the X-Agent-ID header; no tool takes a bank.\n\n" + protocol(agent)
        + "\n## Connected services (Reactor)\n\nYou have the user's connected services through the `reactor` MCP server.\n\n" + REACTOR
    )


def ICON(name):
    return (ROOT / f"shared/assets/{name}.svg").read_text()


def PNG():
    return (ROOT / "shared/assets/mission-control.png").read_bytes()


TARGETS = {
    "plugins/cursor/rules/hippocampus.mdc": lambda: rule(CLIENTS["cursor"]),
    "plugins/cursor/skills/hippocampus/SKILL.md": lambda: skill(CLIENTS["cursor"]),
    "assets/mission-control.svg": lambda: ICON("mission-control"),
    "plugins/claude-code/assets/icon.svg": lambda: ICON("mission-control"),
    "plugins/codex/assets/icon.svg": lambda: ICON("mission-control"),
    "plugins/cursor/assets/icon.svg": lambda: ICON("mission-control"),
    "plugins/openclaw/assets/icon.svg": lambda: ICON("mission-control"),
    "plugins/codex/AGENTS.md": lambda: agents_md(CLIENTS["codex"]),
    "plugins/codex/skills/hippocampus/SKILL.md": lambda: skill(CLIENTS["codex"]),
    "plugins/codex/skills/reactor/SKILL.md": reactor_skill,
    "plugins/cursor/skills/reactor/SKILL.md": reactor_skill,
    "plugins/cursor/rules/reactor.mdc": reactor_rule,
    "plugins/claude-code/skills/reactor/SKILL.md": reactor_skill,
    "plugins/openclaw/skills/reactor/SKILL.md": reactor_skill,
    "plugins/claude-app/skills/reactor/SKILL.md": reactor_skill,
    "plugins/claude-app/skills/hippocampus/SKILL.md": lambda: skill("claude-app"),
    "assets/mission-control.png": PNG,
    "plugins/claude-app/assets/icon.png": PNG,
    "plugins/chatgpt/assets/logo.png": PNG,
    "plugins/chatgpt/assets/icon.png": PNG,
    "plugins/codex/assets/icon.png": PNG,
    "plugins/cursor/assets/icon.png": PNG,
    "plugins/claude-code/assets/icon.png": PNG,
    "plugins/openclaw/assets/icon.png": PNG,
    "plugins/chatgpt/skills/reactor/SKILL.md": reactor_skill,
    "plugins/chatgpt/skills/hippocampus/SKILL.md": lambda: skill("chatgpt"),
    "plugins/openclaw/skills/hippocampus/SKILL.md": lambda: skill("openclaw"),
}

URL = "https://api.nighthawklabs.org/memory/mcp"
# file -> the X-Agent-ID it must send
IDENTITY = {
    "plugins/cursor/mcp.json": "cursor",
    "plugins/codex/config.toml": "codex",
    "plugins/codex/.mcp.json": "codex",
    "plugins/openclaw/config.ts": "openclaw",
    "plugins/claude-code/.mcp.json": "claude-code",
    "plugins/claude-app/.mcp.json": "claude-app",
    "plugins/chatgpt/.mcp.json": "chatgpt",
}
wrong = []
for path, agent in IDENTITY.items():
    text = (ROOT / path).read_text()
    if URL not in text and "MEMORY_MCP_URL" not in text:
        wrong.append(f"{path}: endpoint is not {URL}")
    if agent not in text:
        wrong.append(f"{path}: agent id is not {agent}")

HUB = "https://api.nighthawklabs.org/hub/mcp"
# every client must register the hub, so Hippocampus and Reactor are available everywhere
for path in ["plugins/cursor/mcp.json", "plugins/codex/.mcp.json", "plugins/codex/config.toml", "plugins/claude-code/.mcp.json", "plugins/openclaw/templates/openclaw.jsonc", "plugins/claude-app/.mcp.json", "plugins/chatgpt/.mcp.json"]:
    if HUB not in (ROOT / path).read_text():
        wrong.append(f"{path}: reactor endpoint is not {HUB}")

stale = []
for path, render in TARGETS.items():
    out, want = ROOT / path, render()
    if "--check" in sys.argv:
        if not out.exists() or (out.read_bytes() if isinstance(want, bytes) else out.read_text()) != want:
            stale.append(path)
    else:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(want) if isinstance(want, bytes) else out.write_text(want)
if wrong:
    print("inconsistent:", *wrong, sep="\n  ")
    sys.exit(1)
if stale:
    print("out of date (run scripts/sync-shared.py):", *stale, sep="\n  ")
    sys.exit(1)
