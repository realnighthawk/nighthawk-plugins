#!/usr/bin/env python3
"""Renders the memory protocol in shared/ into each client's instruction files.

    python3 scripts/sync-shared.py          # write
    python3 scripts/sync-shared.py --check  # exit 1 if a generated file is out of date

One source (shared/protocol.md, shared/tools.md), one line of per-client facts below. The endpoint
and bank label are the same everywhere, so they live here once.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROTOCOL = (ROOT / "shared/protocol.md").read_text()
TOOLS = (ROOT / "shared/tools.md").read_text()
NOTE = "<!-- Generated by scripts/sync-shared.py from shared/. Edit shared/, not this file. -->\n"

CLIENTS = {
    "cursor": "cursor",
    "codex": "codex",
}


def protocol(agent: str) -> str:
    return PROTOCOL.replace("{{AGENT}}", agent)


def rule(agent):
    return (
        "---\ndescription: Use Hippocampus long-term memory (recall at the start, retain what should outlive the session)\n"
        "alwaysApply: true\n---\n" + NOTE + "\nYou have long-term memory through the `hippocampus` MCP server.\n\n" + protocol(agent)
    )


def skill(agent):
    return (
        "---\nname: hippocampus\ndescription: Use the Hippocampus MCP as the user's long-term memory. Use when the task depends on "
        "what the user decided, prefers, or did in earlier sessions, or when the user says remember, recall, or forget.\n---\n"
        + NOTE + "\n# Hippocampus memory\n\nOne bank per agent: your bank is named by the `X-Agent-ID` header (`{agent}`); no tool takes a bank. "
        f"Your calls are recorded as the agent `{agent}` (the `X-Agent-ID` header), so what you did and what the user said stay distinguishable.\n\n"
        + TOOLS + "\n" + protocol(agent)
    )


def agents_md(agent):
    return (
        NOTE + "## Long-term memory (Hippocampus)\n\nYou have long-term memory through the `hippocampus` MCP server. "
        f"One bank per agent: yours is '{agent}', named by the X-Agent-ID header; no tool takes a bank.\n\n" + protocol(agent)
    )


TARGETS = {
    "plugins/cursor/rules/hippocampus.mdc": lambda: rule(CLIENTS["cursor"]),
    "plugins/cursor/skills/hippocampus/SKILL.md": lambda: skill(CLIENTS["cursor"]),
    "plugins/codex/AGENTS.md": lambda: agents_md(CLIENTS["codex"]),
}

URL = "https://api.nighthawklabs.org/memory/mcp"
# file -> the X-Agent-ID it must send
IDENTITY = {
    "plugins/cursor/mcp.json": "cursor",
    "plugins/codex/config.toml": "codex",
    "plugins/openclaw/config.ts": "openclaw",
    "plugins/claude-code/.mcp.json": "claude-code",
}
wrong = []
for path, agent in IDENTITY.items():
    text = (ROOT / path).read_text()
    if URL not in text and "MEMORY_MCP_URL" not in text:
        wrong.append(f"{path}: endpoint is not {URL}")
    if agent not in text:
        wrong.append(f"{path}: agent id is not {agent}")

stale = []
for path, render in TARGETS.items():
    out, want = ROOT / path, render()
    if "--check" in sys.argv:
        if not out.exists() or out.read_text() != want:
            stale.append(path)
    else:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(want)
if wrong:
    print("inconsistent:", *wrong, sep="\n  ")
    sys.exit(1)
if stale:
    print("out of date (run scripts/sync-shared.py):", *stale, sep="\n  ")
    sys.exit(1)
